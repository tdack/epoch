/**
 * Decode ANSEL bytes. The two-part ligature and double tilde use the Unicode half marks rather than
 * LC's preferred U+0361 and U+0360: those need the second half dropped, and the halves round-trip.
 */
export function decodeAnsel(bytes: Uint8Array): string {
	let out = '';
	let pending = '';
	for (const byte of bytes) {
		const mark = COMBINING[byte];
		if (mark !== undefined) {
			pending += String.fromCodePoint(mark);
			continue;
		}
		const code = byte < 0x80 ? byte : (SPACING[byte] ?? 0xfffd);
		// A mark before a line break has no letter to sit on; it stays where it was rather than
		// moving onto the next line's level number.
		if (pending && (code === 0x0a || code === 0x0d)) {
			out += pending;
			pending = '';
		}
		out += String.fromCodePoint(code) + pending;
		pending = '';
	}
	return (out + pending).normalize('NFC');
}
